// Copies each website template's index.html, style.css and (if it has one) script.js from public/site-templates
// into src/lib/code/site-template-sources.ts, so the server can seed new projects
// without reading files at runtime. Run after editing a template:
//   node scripts/site-templates.mjs
// tests/site-templates.test.ts fails when the copy is out of date.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ids = ["launchpad-saas", "atelier-portfolio", "form-found-store", "journal-personal", "nova-creative-agency"];
const root = join(import.meta.dirname, "..");
const sources = Object.fromEntries(
  ids.map((id) => {
    const dir = join(root, "public/site-templates", id);
    const js = existsSync(join(dir, "script.js")) ? { js: readFileSync(join(dir, "script.js"), "utf8") } : {};
    return [id, { html: readFileSync(join(dir, "index.html"), "utf8"), css: readFileSync(join(dir, "style.css"), "utf8"), ...js }];
  }),
);
const out = `// Generated by scripts/site-templates.mjs from public/site-templates/<id>/index.html, style.css and script.js. Don't edit by hand.
export const SITE_TEMPLATE_SOURCES: Record<string, { html: string; css: string; js?: string }> = ${JSON.stringify(sources, null, 2)};
`;
writeFileSync(join(root, "src/lib/code/site-template-sources.ts"), out);
console.log(`Wrote ${ids.length} templates to src/lib/code/site-template-sources.ts`);
