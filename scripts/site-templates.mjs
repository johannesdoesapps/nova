// Copies each website template's index.html and style.css from public/site-templates
// into src/lib/code/site-template-sources.ts, so the server can seed new projects
// without reading files at runtime. Run after editing a template:
//   node scripts/site-templates.mjs
// tests/site-templates.test.ts fails when the copy is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ids = ["launchpad-saas", "atelier-portfolio", "form-found-store", "journal-personal"];
const root = join(import.meta.dirname, "..");
const sources = Object.fromEntries(
  ids.map((id) => [id, { html: readFileSync(join(root, "public/site-templates", id, "index.html"), "utf8"), css: readFileSync(join(root, "public/site-templates", id, "style.css"), "utf8") }]),
);
const out = `// Generated by scripts/site-templates.mjs from public/site-templates/<id>/index.html and style.css. Don't edit by hand.
export const SITE_TEMPLATE_SOURCES: Record<string, { html: string; css: string }> = ${JSON.stringify(sources, null, 2)};
`;
writeFileSync(join(root, "src/lib/code/site-template-sources.ts"), out);
console.log(`Wrote ${ids.length} templates to src/lib/code/site-template-sources.ts`);
